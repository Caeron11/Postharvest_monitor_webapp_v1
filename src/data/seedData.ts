function buildSeries(
  temps: number[],
  hums: number[],
  co2s: number[],
  gases: number[]
): TelemetryPoint[] {
  const labels = [
    '06:00',
    '09:00',
    '12:00',
    '15:00',
    '18:00',
    '21:00',
    '00:00',
    '03:00',
    '06:00',
  ];
  return labels.map((hourLabel, i) => ({
    hourLabel,
    tempC: temps[i],
    humidityPct: hums[i],
    co2Ppm: co2s[i],
    gasIndex: gases[i],
  }));
}

